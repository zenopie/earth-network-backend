#!/usr/bin/env python3
"""Regenerate requirements.lock: requirements.txt's whole tree, pinned with hashes.

    bin/lock-requirements.py            # needs network (PyPI)

The image installs with `pip install --require-hashes --only-binary=:all:
--no-deps -r requirements.lock` (audit-5 L12), so every file that runs under
the hot key is one whose sha256 was recorded here. The tree is resolved for
the image's platform (CPython 3.11, manylinux x86_64, wheels only), not this
machine's, and each pin lists the hash of every file PyPI has for that
version, so pip may pick whichever wheel fits.

Bump a dependency in requirements.txt, run this, and commit both files.
"""
import json
import os
import ssl
import subprocess
import sys
import tempfile
import urllib.request

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GLIBC = ["2_17", "2_24", "2_26", "2_27", "2_28", "2_31", "2_34", "2_35", "2_36"]  # bookworm: 2.36


def resolve(work: str) -> list[tuple[str, str]]:
    report = os.path.join(work, "report.json")
    plats = [a for g in GLIBC for a in ("--platform", f"manylinux_{g}_x86_64")]
    plats += ["--platform", "manylinux2014_x86_64", "--platform", "manylinux2010_x86_64",
              "--platform", "manylinux1_x86_64"]
    subprocess.check_call([sys.executable, "-m", "pip", "install", "--quiet", "--dry-run", "--ignore-installed",
                           "--report", report, "--target", os.path.join(work, "t"), *plats,
                           "--python-version", "3.11", "--implementation", "cp",
                           "--abi", "cp311", "--abi", "abi3", "--abi", "none", "--only-binary=:all:",
                           "-r", os.path.join(HERE, "requirements.txt")])
    return sorted((i["metadata"]["name"], i["metadata"]["version"]) for i in json.load(open(report))["install"])


def _tls():
    try:
        import certifi  # a Python whose own CA store is missing (some builds)
    except ImportError:
        return None
    return ssl.create_default_context(cafile=certifi.where())


def hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60, context=_tls()) as r:
        files = json.load(r)["urls"]
    return sorted({f["digests"]["sha256"] for f in files})


def main() -> None:
    with tempfile.TemporaryDirectory() as work:
        pins = resolve(work)
    out = ["# Generated by bin/lock-requirements.py from requirements.txt: do not edit.",
           "# CPython 3.11, manylinux x86_64, wheels only; installed with --require-hashes."]
    for name, version in pins:
        out.append(f"{name}=={version} \\")
        hs = hashes(name, version)
        out += [f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else "") for i, h in enumerate(hs)]
    open(os.path.join(HERE, "requirements.lock"), "w").write("\n".join(out) + "\n")
    print(f"requirements.lock: {len(pins)} packages")


if __name__ == "__main__":
    main()
